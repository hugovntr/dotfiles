import fs from "fs";
import path from "path";
import yaml from "js-yaml";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DOTFILES_DIR = path.resolve(__dirname, "../..");
const THEMES_DIR = path.join(DOTFILES_DIR, "themes");

// Output paths
const GHOSTTY_THEMES_DIR = path.join(
  DOTFILES_DIR,
  "ghostty/.config/ghostty/themes",
);
const GHOSTTY_SELECTION_PATH = path.join(
  DOTFILES_DIR,
  "ghostty/.config/ghostty/theme_selection",
);
const NVIM_GENERATED_PATH = path.join(
  DOTFILES_DIR,
  "nvim/.config/nvim/lua/custom/unified/generated.lua",
);

interface ThemePalette {
  black: string;
  red: string;
  green: string;
  yellow: string;
  blue: string;
  magenta: string;
  cyan: string;
  white: string;
  bright_black: string;
  bright_red: string;
  bright_green: string;
  bright_yellow: string;
  bright_blue: string;
  bright_magenta: string;
  bright_cyan: string;
  bright_white: string;
}

interface ThemeDefinition {
  background: string;
  foreground: string;
  cursor: string;
  selection_bg: string;
  selection_fg: string;
  palette: ThemePalette;
}

interface Overrides {
  palette?: Partial<ThemeDefinition & ThemePalette>;
  neovim?: {
    highlights?: Record<string, Record<string, any>>;
  };
  ghostty?: Record<string, any>;
}

interface ThemeConfig {
  mode: "auto" | "dark" | "light";
  dark: ThemeDefinition;
  light: ThemeDefinition;
  overrides?: {
    dark?: Overrides;
    light?: Overrides;
  };
}

function applyPaletteOverrides(
  base: ThemeDefinition,
  overrides?: Overrides,
): ThemeDefinition {
  if (!overrides?.palette) return base;

  const merged = { ...base };
  const p = overrides.palette;
  const basePalette = { ...base.palette };

  // Apply top-level overrides
  if (p.background) merged.background = p.background;
  if (p.foreground) merged.foreground = p.foreground;
  if (p.cursor) merged.cursor = p.cursor;
  if (p.selection_bg) merged.selection_bg = p.selection_bg;
  if (p.selection_fg) merged.selection_fg = p.selection_fg;

  // Apply palette overrides
  // We iterate over the 16 ansi color keys
  const paletteKeys: (keyof ThemePalette)[] = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "bright_black",
    "bright_red",
    "bright_green",
    "bright_yellow",
    "bright_blue",
    "bright_magenta",
    "bright_cyan",
    "bright_white",
  ];

  for (const key of paletteKeys) {
    if (p[key]) {
      basePalette[key] = p[key]!;
    }
  }

  merged.palette = basePalette;
  return merged;
}

function generateGhosttyTheme(
  theme: ThemeDefinition,
  name: string,
  overrides?: Overrides,
): string {
  const lines = [
    `# Generated by set-theme.ts - ${name}`,
    `background = ${theme.background}`,
    `foreground = ${theme.foreground}`,
    `cursor-color = ${theme.cursor}`,
    `selection-background = ${theme.selection_bg}`,
    `selection-foreground = ${theme.selection_fg}`,
    ``,
    `# Palette`,
    `palette = 0=${theme.palette.black}`,
    `palette = 1=${theme.palette.red}`,
    `palette = 2=${theme.palette.green}`,
    `palette = 3=${theme.palette.yellow}`,
    `palette = 4=${theme.palette.blue}`,
    `palette = 5=${theme.palette.magenta}`,
    `palette = 6=${theme.palette.cyan}`,
    `palette = 7=${theme.palette.white}`,
    `palette = 8=${theme.palette.bright_black}`,
    `palette = 9=${theme.palette.bright_red}`,
    `palette = 10=${theme.palette.bright_green}`,
    `palette = 11=${theme.palette.bright_yellow}`,
    `palette = 12=${theme.palette.bright_blue}`,
    `palette = 13=${theme.palette.bright_magenta}`,
    `palette = 14=${theme.palette.bright_cyan}`,
    `palette = 15=${theme.palette.bright_white}`,
  ];

  if (overrides?.ghostty) {
    lines.push(``);
    lines.push(`# Overrides`);
    for (const [key, val] of Object.entries(overrides.ghostty)) {
      lines.push(`${key} = ${val}`);
    }
  }

  return lines.join("\n");
}

function generateGhosttySelection(mode: string): string {
  if (mode === "auto") {
    return `theme = light:generated-light,dark:generated-dark`;
  } else {
    return `theme = generated-${mode}`;
  }
}

function generateNeovimLua(
  config: ThemeConfig,
  darkTheme: ThemeDefinition,
  lightTheme: ThemeDefinition,
) {
  // Helper to format table
  const fmtTable = (t: ThemeDefinition, overrides?: Overrides) => {
    const c = t.palette;

    let highlightsStr = "nil";
    if (overrides?.neovim?.highlights) {
      const hls = [];
      for (const [group, opts] of Object.entries(overrides.neovim.highlights)) {
        // Convert JS object to Lua table string
        // e.g. { fg: "#fff", bold: true } -> { fg = "#fff", bold = true }
        const optsStr = Object.entries(opts)
          .map(([k, v]) => {
            if (typeof v === "boolean") return `${k} = ${v}`;
            if (typeof v === "number") return `${k} = ${v}`;
            return `${k} = "${v}"`;
          })
          .join(", ");
        hls.push(`    ["${group}"] = { ${optsStr} }`);
      }
      highlightsStr = `{\n${hls.join(",\n")}\n  }`;
    }

    return `{
    colors = {
      bg = "${t.background}",
      fg = "${t.foreground}",
      cursor = "${t.cursor}",
      sel_bg = "${t.selection_bg}",
      sel_fg = "${t.selection_fg}",
      
      black = "${c.black}",
      red = "${c.red}",
      green = "${c.green}",
      yellow = "${c.yellow}",
      blue = "${c.blue}",
      magenta = "${c.magenta}",
      cyan = "${c.cyan}",
      white = "${c.white}",
      
      bright_black = "${c.bright_black}",
      bright_red = "${c.bright_red}",
      bright_green = "${c.bright_green}",
      bright_yellow = "${c.bright_yellow}",
      bright_blue = "${c.bright_blue}",
      bright_magenta = "${c.bright_magenta}",
      bright_cyan = "${c.bright_cyan}",
      bright_white = "${c.bright_white}",
    },
    highlights = ${highlightsStr}
  }`;
  };

  return `
-- Generated by set-theme.ts
local M = {}

M.mode = "${config.mode}"

M.dark = ${fmtTable(darkTheme, config.overrides?.dark)}

M.light = ${fmtTable(lightTheme, config.overrides?.light)}

return M
`;
}

async function main() {
  const themeName = process.argv[2];
  if (!themeName) {
    console.error("Usage: bun run set-theme.ts <theme_name>");
    console.log("Available themes:");
    fs.readdirSync(THEMES_DIR).forEach((f) => {
      if (f.endsWith(".yaml")) console.log(` - ${f.replace(".yaml", "")}`);
    });
    process.exit(1);
  }

  const themePath = path.join(THEMES_DIR, `${themeName}.yaml`);
  if (!fs.existsSync(themePath)) {
    console.error(`Theme file not found: ${themePath}`);
    process.exit(1);
  }

  try {
    const fileContents = fs.readFileSync(themePath, "utf8");
    const config = yaml.load(fileContents) as ThemeConfig;

    if (!config.light && config.dark) {
      config.light = config.dark;
    }
    if (!config.dark && config.light) {
      config.dark = config.light;
    }

    // Apply palette overrides
    const darkTheme = applyPaletteOverrides(
      config.dark,
      config.overrides?.dark,
    );
    const lightTheme = applyPaletteOverrides(
      config.light,
      config.overrides?.light,
    );

    // 1. Generate Ghostty Files
    const ghosttyDark = generateGhosttyTheme(
      darkTheme,
      "dark",
      config.overrides?.dark,
    );
    const ghosttyLight = generateGhosttyTheme(
      lightTheme,
      "light",
      config.overrides?.light,
    );
    const ghosttySelection = generateGhosttySelection(config.mode);

    fs.writeFileSync(
      path.join(GHOSTTY_THEMES_DIR, "generated-dark"),
      ghosttyDark,
    );
    fs.writeFileSync(
      path.join(GHOSTTY_THEMES_DIR, "generated-light"),
      ghosttyLight,
    );
    fs.writeFileSync(GHOSTTY_SELECTION_PATH, ghosttySelection);
    console.log(`Updated Ghostty themes and selection.`);

    // 2. Generate Neovim Lua
    const nvimLua = generateNeovimLua(config, darkTheme, lightTheme);
    fs.writeFileSync(NVIM_GENERATED_PATH, nvimLua);
    console.log(`Updated Neovim generated theme at ${NVIM_GENERATED_PATH}`);
  } catch (e) {
    console.error("Error generating theme:", e);
  }
}

main();
